def fix(t):
    t = t.replace("\u2f01", "，").replace("﹑", "，")   # 4711 的轉錄用了怪頓號
    t = re.sub(r"[ \u3000]+", "", t)                  # 4716 的轉錄夾了空白
    for a, b in FIX:
        t = t.replace(a, b)
    return t.strip()


BREAK_AFTER = "的了是啊嗎吧呢就也都很個那這我你他它們到把被在有會不"


def _cut(p):
    """在 MAXLEN 附近找一個不會把詞切一半的位置。"""
    for i in range(MAXLEN, max(MAXLEN - 5, 1), -1):
        if p[i - 1] in BREAK_AFTER:
            return i
    return MAXLEN


def split_text(t):
    """先按標點切，每段 ≤MAXLEN（兩行）就交給工具折行。回傳 [(文字, 佔比)]。"""
    t = re.sub("(?<=[0-9])\\.(?=[0-9])", "\u2024", t)  # 小數點不當斷句點
    parts = [p for p in re.split(r"[，、。！？?,!.]", t) if p.strip()]
    parts = [p.replace("\u2024", ".") for p in parts]
    out = []
    for p in parts:
        p = p.strip()
        while len(p) > MAXLEN:
            i = _cut(p)
            out.append(p[:i])
            p = p[i:]
        if p:
            out.append(p)
    total = sum(len(p) for p in out) or 1
    return [(p, len(p) / total) for p in out]


