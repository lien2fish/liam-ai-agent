def stat(head, big, note=""):
    return {"kind": "stat", "head": head, "big": big, "note": note}


def bars(head, items):
    return {
        "kind": "bars",
        "head": head,
        "bars": [{"label": a, "v": v, "show": s} for a, v, s in items],
    }


def cal(head, items):
    return {
        "kind": "calendar",
        "head": head,
        "items": [{"date": a, "what": b} for a, b in items],
    }


